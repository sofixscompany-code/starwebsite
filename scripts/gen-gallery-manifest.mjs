import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, "..");
const galleryDir = join(projectRoot, "public", "gallery");
const outFile = join(projectRoot, "src", "data", "gallery-manifest.ts");

const EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);

let files = [];
try {
  files = readdirSync(galleryDir)
    .filter((name) => EXTENSIONS.has(name.slice(name.lastIndexOf(".")).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
} catch (err) {
  console.warn(`[gen-gallery-manifest] Skipping: ${err.message}`);
}

const lines = files.map((name) => `  ${JSON.stringify(`/gallery/${name}`)},`).join("\n");
const manifest = files.length > 0 ? `[\n${lines}\n]` : `[]`;

const content = `// AUTO-GENERATED by scripts/gen-gallery-manifest.mjs - do not edit manually.
// Regenerated automatically on every build/dev start.

export const GALLERY_MANIFEST: string[] = ${manifest};

export const GALLERY_MANIFEST_COUNT = ${files.length};
`;

writeFileSync(outFile, content, "utf8");
console.log(`[gen-gallery-manifest] ${files.length} gallery images written to ${outFile}`);
