/**
 * Generates src/data/nepal-geo.ts from the open NepalGeoData dataset
 * (753 local levels + ward lists).
 *
 * Source: https://github.com/whoamisafal/NepalGeoData (nepali_dataset.json)
 * Re-run when administrative data changes:
 *   curl -sL -o /tmp/nepali_dataset.json https://raw.githubusercontent.com/whoamisafal/NepalGeoData/main/nepali_dataset.json
 *   node scripts/generate-nepal-geo.mjs /tmp/nepali_dataset.json
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/generate-nepal-geo.mjs <nepali_dataset.json>");
  process.exit(1);
}

/** Official English province names (dataset uses a few legacy spellings). */
const PROVINCE_NAME = {
  "Koshi Province": "Koshi Province",
  "Madhesh Province": "Madhesh Province",
  Bagmati: "Bagmati Province",
  Gandaki: "Gandaki Province",
  Lumbini: "Lumbini Province",
  Karnali: "Karnali Province",
  "Sudur Paschimanchal": "Sudurpashchim Province",
};

const PROVINCE_ORDER = [
  "Koshi Province",
  "Madhesh Province",
  "Bagmati Province",
  "Gandaki Province",
  "Lumbini Province",
  "Karnali Province",
  "Sudurpashchim Province",
];

const TYPE_SUFFIXES = [
  [" Sub-Metropolitan City", "Sub-Metropolitan City"],
  [" Metropolitan City", "Metropolitan City"],
  [" Rural Municipality", "Rural Municipality"],
  [" Municipality", "Municipality"],
];

const raw = JSON.parse(readFileSync(src, "utf8"));

/** @type {Record<string, Record<string, Map<string, {type: string, wards: number}>>>} */
const tree = {};
let bad = 0;

for (const row of raw) {
  const province = PROVINCE_NAME[row.state] ?? row.state;
  const match = TYPE_SUFFIXES.find(([suffix]) => row.municipality.endsWith(suffix));
  if (!match || !Array.isArray(row.wards) || row.wards.length === 0) {
    bad++;
    continue;
  }
  tree[province] ??= {};
  tree[province][row.district] ??= new Map();
  tree[province][row.district].set(row.municipality, {
    type: match[1],
    wards: Math.max(...row.wards),
  });
}

if (bad > 0) console.warn(`Skipped ${bad} rows without a recognised type/wards`);

const sortAlpha = (a, b) => a.localeCompare(b, "en");

const provinces = PROVINCE_ORDER.filter((p) => tree[p])
  .map((province) => ({
    name: province,
    districts: Object.keys(tree[province])
      .sort(sortAlpha)
      .map((district) => ({
        name: district,
        municipalities: [...tree[province][district].entries()]
          .map(([name, m]) => ({ name, type: m.type, wards: m.wards }))
          .sort((a, b) => sortAlpha(a.name, b.name)),
      })),
  }))
  .sort((a, b) => PROVINCE_ORDER.indexOf(a.name) - PROVINCE_ORDER.indexOf(b.name));

const totalDistricts = provinces.reduce((n, p) => n + p.districts.length, 0);
const totalMunicipalities = provinces.reduce(
  (n, p) => n + p.districts.reduce((m, d) => m + d.municipalities.length, 0),
  0,
);
console.log(
  `provinces=${provinces.length} districts=${totalDistricts} municipalities=${totalMunicipalities}`,
);

const out = `/* AUTO-GENERATED by scripts/generate-nepal-geo.mjs — do not edit by hand.
 * Source: NepalGeoData (nepali_dataset.json) — 7 provinces, 77 districts,
 * 753 local levels with real ward counts.
 * Regenerate: node scripts/generate-nepal-geo.mjs <nepali_dataset.json>
 */

export type MunicipalityType =
  | "Rural Municipality"
  | "Municipality"
  | "Sub-Metropolitan City"
  | "Metropolitan City";

export interface Municipality {
  name: string;
  type: MunicipalityType;
  /** Actual number of wards for this local level (5–46). */
  wards: number;
}

export interface District {
  name: string;
  municipalities: Municipality[];
}

export interface Province {
  name: string;
  districts: District[];
}

export const NEPAL_GEO: Province[] = ${JSON.stringify(provinces)};

export const PROVINCES: string[] = NEPAL_GEO.map((p) => p.name);

export function districtsFor(province: string): District[] {
  return NEPAL_GEO.find((p) => p.name === province)?.districts ?? [];
}

export function municipalitiesFor(province: string, district: string): Municipality[] {
  return districtsFor(province).find((d) => d.name === district)?.municipalities ?? [];
}

export function municipalityInfo(
  province: string,
  district: string,
  municipality: string,
): Municipality | undefined {
  return municipalitiesFor(province, district).find((m) => m.name === municipality);
}

/** Ward options generated from the selected municipality's real ward count. */
export function wardsFor(province: string, district: string, municipality: string): number[] {
  const info = municipalityInfo(province, district, municipality);
  if (!info) return [];
  return Array.from({ length: info.wards }, (_, i) => i + 1);
}
`;

const __dirname = dirname(fileURLToPath(import.meta.url));
const dest = resolve(__dirname, "../src/data/nepal-geo.ts");
writeFileSync(dest, out, "utf-8");
console.log(`wrote ${dest} (${(out.length / 1024).toFixed(1)} KB)`);
